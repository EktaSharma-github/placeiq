-- =====================================================================
--  PlaceIQ : Campus Placement & Recruitment Management System
--  FDS Course Project  |  Phase 2 : DDL
--
--  Target   : PostgreSQL 15+  (developed on PostgreSQL 18)
--             15+ is needed for  ON DELETE SET NULL (column_list)
--  Run      : createdb -U postgres placeiq
--             psql -U postgres -d placeiq -f 02_ddl.sql
--  Re-run   : safe; the whole schema is dropped and rebuilt.
--
--  Conventions
--    * Every table is in BCNF (see 01_design.md, section 5).
--    * Surrogate keys are IDENTITY columns; natural keys are kept as
--      UNIQUE constraints (alternate keys) so no business rule is lost.
--    * Business-rule tags (BR-n) refer to the catalogue in 01_design.md.
--    * Rules that span several tables (eligibility, one-offer policy,
--      totality of specialisation) are enforced by triggers in Phase 3.
-- =====================================================================

-- btree_gist lets a GiST index mix "=" on integers with "&&" on ranges;
-- we need it for the interview double-booking EXCLUDE constraint (BR-8).
CREATE EXTENSION IF NOT EXISTS btree_gist SCHEMA public;

DROP SCHEMA IF EXISTS placeiq CASCADE;
CREATE SCHEMA placeiq;
SET search_path TO placeiq, public;


-- =====================================================================
-- 1. REFERENCE ENTITIES
-- =====================================================================

CREATE TABLE program (
    program_id       SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code     VARCHAR(10)  NOT NULL UNIQUE,                   -- alternate key
    program_name     VARCHAR(100) NOT NULL,
    duration_months  SMALLINT     NOT NULL CHECK (duration_months BETWEEN 6 AND 36)
);

CREATE TABLE placement_cycle (
    cycle_id       SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_name     VARCHAR(60) NOT NULL UNIQUE,                      -- alternate key
    cycle_type     VARCHAR(10) NOT NULL CHECK (cycle_type IN ('SUMMER', 'FINAL', 'LATERAL')),
    academic_year  VARCHAR(7)  NOT NULL CHECK (academic_year ~ '^[0-9]{4}-[0-9]{2}$'),  -- e.g. 2026-27
    start_date     DATE        NOT NULL,
    end_date       DATE        NOT NULL,
    CONSTRAINT chk_cycle_dates CHECK (end_date >= start_date),
    CONSTRAINT uq_cycle_type_year UNIQUE (cycle_type, academic_year) -- third candidate key
);

CREATE TABLE skill (
    skill_id    SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name  VARCHAR(50) NOT NULL UNIQUE
);


-- =====================================================================
-- 2. PERSON GENERALISATION HIERARCHY
--    person  -->  student | recruiter | committee_member | alumnus
--    Overlapping, partial specialisation: a student may also sit on the
--    placement committee, so a person_id may appear in several subtypes.
--    Mapping: one table per subclass, sharing the superclass PK.
-- =====================================================================

CREATE TABLE person (
    person_id   INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50),
    email       VARCHAR(120) NOT NULL UNIQUE,                        -- alternate key
    phone       VARCHAR(15)  UNIQUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_person_email CHECK (email = lower(email) AND email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT chk_person_phone CHECK (phone ~ '^\+?[0-9]{10,14}$')
);

-- Placement status (PLACED / UNPLACED) is a DERIVED attribute: it is
-- computed from offer in a view (Phase 3), never stored, so it can never
-- disagree with the offers table.
CREATE TABLE student (
    person_id        INT          PRIMARY KEY REFERENCES person (person_id) ON DELETE CASCADE,
    roll_no          VARCHAR(12)  NOT NULL UNIQUE,                   -- alternate key (BR-2)
    program_id       SMALLINT     NOT NULL REFERENCES program (program_id) ON DELETE RESTRICT,  -- BR-1
    batch_year       SMALLINT     NOT NULL CHECK (batch_year BETWEEN 2000 AND 2100),
    cgpa             NUMERIC(4,2) NOT NULL CHECK (cgpa BETWEEN 0 AND 10),                      -- BR-3
    active_backlogs  SMALLINT     NOT NULL DEFAULT 0 CHECK (active_backlogs >= 0),
    opted_out        BOOLEAN      NOT NULL DEFAULT FALSE             -- opted out of placements
);

CREATE TABLE committee_member (
    person_id   INT         PRIMARY KEY REFERENCES person (person_id) ON DELETE CASCADE,
    cc_role     VARCHAR(15) NOT NULL CHECK (cc_role IN ('COORDINATOR', 'SECRETARY', 'MEMBER')),
    term_start  DATE        NOT NULL,
    term_end    DATE        NOT NULL,
    CONSTRAINT chk_cc_term CHECK (term_end > term_start)
);


-- =====================================================================
-- 3. SPONSOR CATEGORY (UNION TYPE)
--    sponsor = company  U  alumnus
--    A surrogate sponsor_id is the key of the category. Each member table
--    carries a constant discriminator column and a composite FK to
--    (sponsor_id, sponsor_type), so a sponsor row typed 'COMPANY' cannot
--    be claimed by an alumnus and vice versa (BR-13).
-- =====================================================================

CREATE TABLE sponsor (
    sponsor_id    INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_type  VARCHAR(10) NOT NULL CHECK (sponsor_type IN ('COMPANY', 'ALUMNUS')),
    CONSTRAINT uq_sponsor_id_type UNIQUE (sponsor_id, sponsor_type)
);

CREATE TABLE company (
    company_id    INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name  VARCHAR(100) NOT NULL UNIQUE,                      -- alternate key
    sector        VARCHAR(15)  NOT NULL CHECK (sector IN ('CONSULTING', 'BFSI', 'TECHNOLOGY', 'FMCG',
                                                          'ANALYTICS', 'E-COMMERCE', 'MANUFACTURING', 'OTHER')),
    hq_city       VARCHAR(50)  NOT NULL,
    website       VARCHAR(200),
    sponsor_id    INT          UNIQUE,                               -- NULL = not a sponsor (partial)
    sponsor_type  VARCHAR(10)  NOT NULL DEFAULT 'COMPANY' CHECK (sponsor_type = 'COMPANY'),
    CONSTRAINT fk_company_sponsor FOREIGN KEY (sponsor_id, sponsor_type)
        REFERENCES sponsor (sponsor_id, sponsor_type) ON DELETE SET NULL (sponsor_id)
);

CREATE TABLE alumnus (
    person_id         INT          PRIMARY KEY REFERENCES person (person_id) ON DELETE CASCADE,
    program_id        SMALLINT     NOT NULL REFERENCES program (program_id) ON DELETE RESTRICT,
    graduation_year   SMALLINT     NOT NULL CHECK (graduation_year BETWEEN 1960 AND 2100),
    current_employer  VARCHAR(100),
    sponsor_id        INT          UNIQUE,
    sponsor_type      VARCHAR(10)  NOT NULL DEFAULT 'ALUMNUS' CHECK (sponsor_type = 'ALUMNUS'),
    CONSTRAINT fk_alumnus_sponsor FOREIGN KEY (sponsor_id, sponsor_type)
        REFERENCES sponsor (sponsor_id, sponsor_type) ON DELETE SET NULL (sponsor_id)
);

CREATE TABLE sponsorship (
    sponsorship_id  INT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sponsor_id      INT           NOT NULL REFERENCES sponsor (sponsor_id) ON DELETE RESTRICT,
    cycle_id        SMALLINT      NOT NULL REFERENCES placement_cycle (cycle_id) ON DELETE RESTRICT,
    purpose         VARCHAR(15)   NOT NULL CHECK (purpose IN ('SCHOLARSHIP', 'EVENT', 'INFRASTRUCTURE', 'AWARD')),
    amount_inr      NUMERIC(12,2) NOT NULL CHECK (amount_inr > 0),
    CONSTRAINT uq_sponsorship UNIQUE (sponsor_id, cycle_id, purpose)
);

-- recruiter needs company, so it is created after it.
CREATE TABLE recruiter (
    person_id    INT         PRIMARY KEY REFERENCES person (person_id) ON DELETE CASCADE,
    company_id   INT         NOT NULL REFERENCES company (company_id) ON DELETE CASCADE,
    designation  VARCHAR(60) NOT NULL,
    CONSTRAINT uq_recruiter_company UNIQUE (person_id, company_id)  -- target of composite FK (BR-5)
);


-- =====================================================================
-- 4. JOB ROLE SPECIALISATION
--    job_role --> internship_role | fulltime_role
--    Disjoint: enforced declaratively via discriminator + composite FK.
--    Total:    enforced by a DEFERRABLE constraint trigger (Phase 3).
-- =====================================================================

CREATE TABLE job_role (
    job_id                INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            INT         NOT NULL REFERENCES company (company_id) ON DELETE RESTRICT,
    cycle_id              SMALLINT    NOT NULL REFERENCES placement_cycle (cycle_id) ON DELETE RESTRICT,
    posted_by             INT,                                       -- recruiter who posted it
    title                 VARCHAR(80) NOT NULL,
    role_type             VARCHAR(10) NOT NULL CHECK (role_type IN ('INTERNSHIP', 'FULLTIME')),
    location              VARCHAR(60) NOT NULL,
    openings              SMALLINT    NOT NULL CHECK (openings > 0),
    application_deadline  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_job_natural_key UNIQUE (company_id, cycle_id, title),  -- natural key kept
    CONSTRAINT uq_job_id_type     UNIQUE (job_id, role_type),            -- target for subtype FKs
    -- BR-5: the posting recruiter must work for the same company.
    CONSTRAINT fk_job_posted_by FOREIGN KEY (posted_by, company_id)
        REFERENCES recruiter (person_id, company_id) ON DELETE SET NULL (posted_by)
);

CREATE TABLE internship_role (
    job_id           INT           PRIMARY KEY,
    role_type        VARCHAR(10)   NOT NULL DEFAULT 'INTERNSHIP' CHECK (role_type = 'INTERNSHIP'),
    stipend_monthly  NUMERIC(10,2) NOT NULL CHECK (stipend_monthly >= 0),
    duration_weeks   SMALLINT      NOT NULL CHECK (duration_weeks BETWEEN 4 AND 26),
    ppo_possible     BOOLEAN       NOT NULL DEFAULT FALSE,           -- pre-placement offer
    CONSTRAINT fk_internship_job FOREIGN KEY (job_id, role_type)
        REFERENCES job_role (job_id, role_type) ON DELETE CASCADE
);

CREATE TABLE fulltime_role (
    job_id         INT           PRIMARY KEY,
    role_type      VARCHAR(10)   NOT NULL DEFAULT 'FULLTIME' CHECK (role_type = 'FULLTIME'),
    ctc_lpa        NUMERIC(6,2)  NOT NULL CHECK (ctc_lpa > 0),       -- lakhs per annum
    fixed_lpa      NUMERIC(6,2)  NOT NULL CHECK (fixed_lpa > 0),
    joining_bonus  NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (joining_bonus >= 0),
    CONSTRAINT chk_fixed_le_ctc CHECK (fixed_lpa <= ctc_lpa),
    CONSTRAINT fk_fulltime_job FOREIGN KEY (job_id, role_type)
        REFERENCES job_role (job_id, role_type) ON DELETE CASCADE
);

-- M:N  job_role x program  (which programs may apply, and the cut-off)
CREATE TABLE eligibility (
    job_id        INT          REFERENCES job_role (job_id) ON DELETE CASCADE,
    program_id    SMALLINT     REFERENCES program (program_id) ON DELETE CASCADE,
    min_cgpa      NUMERIC(4,2) NOT NULL DEFAULT 0 CHECK (min_cgpa BETWEEN 0 AND 10),
    max_backlogs  SMALLINT     NOT NULL DEFAULT 0 CHECK (max_backlogs >= 0),
    PRIMARY KEY (job_id, program_id)
);

-- Multi-valued attribute "skills" of student, mapped to its own relation.
CREATE TABLE student_skill (
    student_id   INT      REFERENCES student (person_id) ON DELETE CASCADE,
    skill_id     SMALLINT REFERENCES skill (skill_id) ON DELETE CASCADE,
    proficiency  SMALLINT NOT NULL CHECK (proficiency BETWEEN 1 AND 5),
    PRIMARY KEY (student_id, skill_id)
);

CREATE TABLE job_required_skill (
    job_id           INT      REFERENCES job_role (job_id) ON DELETE CASCADE,
    skill_id         SMALLINT REFERENCES skill (skill_id) ON DELETE RESTRICT,  -- can't drop a skill a job needs
    min_proficiency  SMALLINT NOT NULL DEFAULT 1 CHECK (min_proficiency BETWEEN 1 AND 5),
    PRIMARY KEY (job_id, skill_id)
);


-- =====================================================================
-- 5. RECRUITMENT PIPELINE
--    application (M:N student x job)  ->  interview (aggregation)  ->  offer
-- =====================================================================

CREATE TABLE application (
    application_id     INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id         INT         NOT NULL REFERENCES student (person_id) ON DELETE CASCADE,
    job_id             INT         NOT NULL REFERENCES job_role (job_id) ON DELETE RESTRICT,
    applied_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    status             VARCHAR(12) NOT NULL DEFAULT 'APPLIED'
                       CHECK (status IN ('APPLIED', 'SHORTLISTED', 'REJECTED', 'WITHDRAWN', 'OFFERED')),
    status_updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_application_student_job UNIQUE (student_id, job_id),     -- BR-6, alternate key
    CONSTRAINT chk_application_times CHECK (status_updated_at >= applied_at)
);

-- Weak entity: a round exists only within a job; identified by (job_id, round_no).
CREATE TABLE interview_round (
    job_id          INT         REFERENCES job_role (job_id) ON DELETE CASCADE,
    round_no        SMALLINT    CHECK (round_no BETWEEN 1 AND 10),
    round_type      VARCHAR(10) NOT NULL CHECK (round_type IN ('APTITUDE', 'GD', 'TECHNICAL', 'CASE', 'HR')),
    is_elimination  BOOLEAN     NOT NULL DEFAULT TRUE,
    PRIMARY KEY (job_id, round_no)
);

-- Aggregation: the relationship "application" is treated as an entity that
-- participates in "evaluated_in" with interview_round.
-- The two composite FKs share job_id, which guarantees a student is only
-- interviewed in a round that belongs to the job they applied for (BR-7).
CREATE TABLE interview (
    student_id  INT,
    job_id      INT,
    round_no    SMALLINT,
    slot_start  TIMESTAMPTZ  NOT NULL,
    slot_end    TIMESTAMPTZ  NOT NULL,
    venue       VARCHAR(40)  NOT NULL,
    result      VARCHAR(11)  NOT NULL DEFAULT 'SCHEDULED'
                CHECK (result IN ('SCHEDULED', 'CLEARED', 'NOT_CLEARED', 'ABSENT')),
    score       NUMERIC(5,2) CHECK (score BETWEEN 0 AND 100),
    PRIMARY KEY (student_id, job_id, round_no),
    CONSTRAINT fk_interview_application FOREIGN KEY (student_id, job_id)
        REFERENCES application (student_id, job_id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_round FOREIGN KEY (job_id, round_no)
        REFERENCES interview_round (job_id, round_no) ON DELETE CASCADE,
    CONSTRAINT chk_slot_order    CHECK (slot_end > slot_start),
    CONSTRAINT chk_slot_length   CHECK (slot_end - slot_start <= INTERVAL '4 hours'),
    CONSTRAINT chk_score_if_done CHECK (result <> 'SCHEDULED' OR score IS NULL),
    -- BR-8: no student may be in two interviews whose time slots overlap.
    CONSTRAINT excl_student_double_booking
        EXCLUDE USING gist (student_id WITH =, tstzrange(slot_start, slot_end) WITH &&)
);

-- 1:1 with application (UNIQUE on the FK columns).
-- The offered pay is NOT stored here: it is a fact about the job
-- (fulltime_role / internship_role); copying it would create a
-- transitive dependency  offer_id -> job_id -> ctc_lpa.
CREATE TABLE offer (
    offer_id           INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id         INT         NOT NULL,
    job_id             INT         NOT NULL,
    offered_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    response_deadline  TIMESTAMPTZ NOT NULL,
    status             VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                       CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'REVOKED', 'EXPIRED')),
    responded_at       TIMESTAMPTZ,
    CONSTRAINT uq_offer_application UNIQUE (student_id, job_id),           -- BR-9
    -- RESTRICT: an offer is a formal record. Deleting a student cascades to
    -- their applications, and this FK then blocks it, so a student who holds
    -- an offer cannot be deleted (BR-15).
    CONSTRAINT fk_offer_application FOREIGN KEY (student_id, job_id)
        REFERENCES application (student_id, job_id) ON DELETE RESTRICT,
    CONSTRAINT chk_offer_deadline CHECK (response_deadline > offered_at),
    -- BR-10: responded_at is filled exactly when the student has responded.
    CONSTRAINT chk_offer_response CHECK ((status IN ('ACCEPTED', 'DECLINED')) = (responded_at IS NOT NULL)),
    CONSTRAINT chk_offer_resp_time CHECK (responded_at IS NULL OR responded_at >= offered_at)
);

-- Audit trail written by the Phase 3 triggers / procedures.
CREATE TABLE placement_log (
    log_id      BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    student_id  INT         REFERENCES student (person_id) ON DELETE SET NULL,
    job_id      INT         REFERENCES job_role (job_id) ON DELETE SET NULL,
    action      VARCHAR(30) NOT NULL,
    details     TEXT,
    logged_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- =====================================================================
-- 6. INDEXES ON FOREIGN KEYS
--    PostgreSQL indexes PRIMARY KEY and UNIQUE columns automatically but
--    NOT foreign-key columns. Without these, every join on the FK, and
--    every ON DELETE check on the parent, scans the whole child table.
--    FKs already covered by the leading column of a PK/UNIQUE are skipped.
--    The analytical indexes (with EXPLAIN ANALYZE before/after) are
--    in Phase 3.
-- =====================================================================

CREATE INDEX idx_student_program        ON student (program_id);
CREATE INDEX idx_alumnus_program        ON alumnus (program_id);
CREATE INDEX idx_recruiter_company      ON recruiter (company_id);
CREATE INDEX idx_sponsorship_cycle      ON sponsorship (cycle_id);
CREATE INDEX idx_job_cycle              ON job_role (cycle_id);
CREATE INDEX idx_job_posted_by          ON job_role (posted_by, company_id);
CREATE INDEX idx_eligibility_program    ON eligibility (program_id);
CREATE INDEX idx_student_skill_skill    ON student_skill (skill_id);
CREATE INDEX idx_job_req_skill_skill    ON job_required_skill (skill_id);
CREATE INDEX idx_application_job        ON application (job_id);
CREATE INDEX idx_interview_round        ON interview (job_id, round_no);
CREATE INDEX idx_offer_job              ON offer (job_id);
CREATE INDEX idx_log_student            ON placement_log (student_id);
CREATE INDEX idx_log_job                ON placement_log (job_id);
